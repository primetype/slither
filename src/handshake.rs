    #[test]
    fn established_datagrams_round_trip() {
        let mut a = identity(0x11, 0xA1);
        let mut b = identity(0x22, 0xB2);
        let mut rng = ChaCha20Rng::from_seed([0xC3; 32]);
        // `recv` is now an epoch-ratcheting half, so `decrypt_at` takes
        // `&mut self` (hiss R0); the responder binding must be mutable.
        let (mut init, mut resp) = run_handshake(&mut a, &mut b, &mut rng);

        // A→B under the Data header AD.
        let ad = crate::wire::DataHeader::new(resp.our_index, 0).to_bytes();
        let mut ct = vec![0u8; 5 + crate::wire::AEAD_TAG_LEN];
        let (counter, n) = init
            .send
            .encrypt_next(&ad, b"hello", &mut ct)
            .expect("seal");
        assert_eq!(counter, 0);
        let mut pt = vec![0u8; n];
        let m = resp
            .recv
            .decrypt_at(counter, &ad, &ct[..n], &mut pt)
            .expect("open");
        assert_eq!(&pt[..m], b"hello");
    }

    /// The key ratchet crosses an epoch boundary transparently, and a datagram
    /// reordered back across that boundary still opens under the receiver's
    /// retained previous-epoch key (hiss keeps the current and the immediately
    /// preceding epoch keys). Driven at the session layer directly — no
    /// endpoint, no frame layer — so a full `REKEY_EPOCH_MSGS` boundary is
    /// crossed in-memory and fast.
    #[tokio::test]
    async fn epoch_boundary_delivers_and_reordered_straggler_opens() {
        use crate::session::{REKEY_EPOCH_MSGS, Session};
        use crate::wire::DataHeader;
        use tokio::time::Instant;

        let mut a = identity(0x11, 0xA1);
        let mut b = identity(0x22, 0xB2);
        let mut rng = ChaCha20Rng::from_seed([0xC3; 32]);
        let (init_est, resp_est) = run_handshake(&mut a, &mut b, &mut rng);

        let addr_a: std::net::SocketAddr = "127.0.0.1:1".parse().expect("addr");
        let addr_b: std::net::SocketAddr = "127.0.0.1:2".parse().expect("addr");
        let now = Instant::now();
        let mut sender = Session::new(init_est, addr_b, now);
        let mut receiver = Session::new(resp_est, addr_a, now);

        let epoch = REKEY_EPOCH_MSGS.get(); // 65_536
        // Seal one full epoch of DATA (send counters 0..epoch, all epoch 0),
        // holding back the LAST epoch-0 packet so it can arrive after the
        // boundary as a reordered straggler.
        let mut held = None;
        for c in 0..epoch {
            let payload = c.to_be_bytes();
            let packet = sender.seal(&payload, now).expect("seal");
            assert_eq!(
                DataHeader::parse(&packet).expect("data").0.counter(),
                c,
                "the mirrored counter tracks the hiss send counter"
            );
            if c == epoch - 1 {
                held = Some((packet, payload));
            } else {
                let got = receiver.open(&packet, addr_a, now).expect("open epoch 0");
                assert_eq!(got.payload, Some(payload.to_vec()));
            }
        }

        // The first epoch-1 packet (counter == epoch): the send key has ratcheted
        // forward, and opening it commits the receiver's ratchet to epoch 1,
        // retaining epoch 0 as the previous key.
        let boundary_payload = epoch.to_be_bytes();
        let boundary = sender
            .seal(&boundary_payload, now)
            .expect("seal across the boundary");
        assert_eq!(
            DataHeader::parse(&boundary).expect("data").0.counter(),
            epoch
        );
        let got = receiver.open(&boundary, addr_a, now).expect("open epoch 1");
        assert_eq!(got.payload, Some(boundary_payload.to_vec()));

        // The held-back epoch-0 packet, reordered to after the boundary, still
        // opens under the retained previous-epoch key — and, one behind the
        // greatest counter, is inside the 128-counter replay window, so it
        // delivers exactly once.
        let (straggler_packet, straggler_payload) = held.expect("held a packet");
        let got = receiver
            .open(&straggler_packet, addr_a, now)
            .expect("the previous-epoch straggler still opens");
        assert_eq!(got.payload, Some(straggler_payload.to_vec()));
    }

