    #[test]
    fn tampered_payload_fails_then_clean_msg1_succeeds() {
        // Flipping one byte of the msg1 timestamp-payload ciphertext (recomputing
        // mac1, which is keyed on a PUBLIC key — an on-path attacker can) makes
        // the msg1 tail's AEAD tag fail inside the read: no RespAccept, so no
        // msg2.
        let mut a = identity(0x11, 0xA1);
        let mut b = identity(0x22, 0xB2);
        let ts = Timestamp { secs: 5, nanos: 5 };
        let (init_packet, _pending) = build_init(
            a.provider(),
            a.static_secret(),
            b.static_public(),
            0x1111_1111,
            ts,
        )
        .expect("init");
        // The payload ciphertext sits after the 6-byte header, the 65-byte
        // plaintext ephemeral, and the 81-byte encrypted static.
        let payload_off = InitHeader::SIZE + 65 + (65 + 16);
        let mut tampered = init_packet.clone();
        tampered[payload_off] ^= 0xFF;
        let tag = mac::compute(&b.static_public(), &tampered[..INIT_MAC_START]);
        tampered[INIT_MAC_START..].copy_from_slice(&tag);
        // The flip is past the encrypted static, so the read sails through the
        // allow-list closure and dies at the payload tail's AEAD tag.
        let allow = allow_of(&[a.static_public()]);
        let result = accept_init(
            b.provider(),
            &b.static_public(),
            b.static_secret(),
            &tampered,
            &allow,
        );
        assert!(
            matches!(result, Err(HsError::Crypto(_))),
            "a tampered payload ciphertext must fail the tail AEAD inside the read"
        );

        // A subsequent clean msg1 succeeds — the tamper poisoned nothing.
        let accept = accept_init(
            b.provider(),
            &b.static_public(),
            b.static_secret(),
            &init_packet,
            &allow,
        )
        .expect("the clean msg1 is accepted");
        assert_eq!(accept.initiator_static(), &a.static_public());
        assert_eq!(accept.timestamp(), ts);
    }

    #[test]
    fn responder_dh_cost_is_staged() {
        // The ruled cost property (2026/07/16), pinned on the responder's
        // provider at the macro read's stage boundaries: a rejected read costs
        // exactly the one `es` DH, an accepted read costs exactly `es` + `ss`,
        // and the msg2 write adds `ee` + `se`. The initiator runs on its own
        // (uncounted) provider, so its DHs cannot pollute the count.
        use std::sync::atomic::Ordering;

        let mut a = identity(0x11, 0xA1);
        let mut b = crate::testutil::CountingIdentity::new(0x22, 0xB2).expect("valid scalar");
        let dh_count = b.dh_count();
        let ts = Timestamp { secs: 3, nanos: 3 };
        let (init_packet, pending) = build_init(
            a.provider(),
            a.static_secret(),
            b.static_public(),
            0x3333_3333,
            ts,
        )
        .expect("init");
        assert_eq!(dh_count.load(Ordering::SeqCst), 0, "no responder DH yet");

        // An unlisted (empty allow-list) read: rejected by the closure after
        // `es`, before `ss` — exactly one DH, no RespAccept.
        let rejected = accept_init(
            b.provider(),
            &b.static_public(),
            b.static_secret(),
            &init_packet,
            &HashSet::new(),
        );
        assert!(matches!(rejected, Err(HsError::Unlisted)));
        assert_eq!(
            dh_count.load(Ordering::SeqCst),
            1,
            "a rejected read costs exactly one DH (`es`)"
        );

        // The same msg1, allow-listed: the accepted read pays `es` + `ss`.
        let allow = HashSet::from([a.static_public().to_compressed()]);
        let accept = accept_init(
            b.provider(),
            &b.static_public(),
            b.static_secret(),
            &init_packet,
            &allow,
        )
        .expect("accept");
        assert_eq!(
            dh_count.load(Ordering::SeqCst),
            1 + 2,
            "an accepted read costs exactly two DHs (`es` + `ss`)"
        );
        assert_eq!(accept.timestamp(), ts);

        let (resp_packet, _est) = accept.accept(0x4444_4444).expect("accept");
        assert_eq!(
            dh_count.load(Ordering::SeqCst),
            1 + 2 + 2,
            "the msg2 write adds `ee` + `se`"
        );

        // Completing the initiator exercises only ITS provider: the responder's
        // count must not move.
        let _ = complete_init(pending, &a.static_public(), &resp_packet).expect("complete");
        assert_eq!(dh_count.load(Ordering::SeqCst), 5);
    }

