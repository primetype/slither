//! The slither IK handshake on hiss's `noise!`-generated sans-io state
//! machines, and the WireGuard-style initiation defences layered around it.
//!
//! The handshake is declared once, in Noise's own notation, by the
//! [`hiss::noise!`] invocation below; hiss generates fixed-size, no-I/O state
//! machines (every message is a `[u8; N]`), so slither frames the messages
//! into its packets directly — no buffer adapters, no blocking driver.
//!
//! # The timestamp rides the encrypted msg1 payload
//!
//! WireGuard puts a monotonic timestamp inside the encrypted handshake-init
//! payload to defeat initiation replay, and slither does exactly the same: the
//! pattern declares a 12-byte **application payload** on msg1 (the `[12]`
//! suffix), the initiator supplies the timestamp to
//! [`write_message_1`](IKInitiatorMsg1::write_message_1), and the responder's
//! read recovers it. On IK msg1 the payload tail is keyed (encrypted after the
//! `e, es, s, ss` tokens), so the timestamp is confidential to the holder of
//! the responder's static — a passive observer never sees the initiator's
//! clock — and a tampered payload ciphertext fails the tail's AEAD tag,
//! failing the handshake. The prologue is the fixed [`PROLOGUE`] constant.
//! Per initiator static the responder keeps the greatest timestamp accepted
//! ([`TimestampGuard`]) and rejects non-greater values.
//!
//! # The allow-list is the read's verification closure
//!
//! [`accept_init`] verifies mac1 (the DoS gate — before any DH), then reads
//! msg1 through the generated
//! [`read_message_1_with`](IKResponderMsg1::read_message_1_with) variant: the
//! initiator's **claimed** static is handed to the closure as soon as `s`
//! decrypts — after the `es` DH, **before** `ss` — and the closure is the
//! allow-list. An unlisted claim is rejected there
//! (`HandshakeError::PeerRejected`, surfaced as [`HsError::Unlisted`]) at the
//! ruled cost of exactly one DH, with no `ss`, no timestamp decryption, and
//! no msg2 (the maintainer, 2026/07/16). At that point the identity is
//! *claimed, not yet proven* — hiss's documented contract for the `_with`
//! reads — so rejecting is always safe; possession of a *listed* claim is
//! proven inside the same accepted read by `ss` and the tail's AEAD tag
//! (a forger of a listed key costs the `ss` DH too, then fails there —
//! WireGuard's exact shape). An accepted read pauses on the [`RespAccept`]:
//! the caller consults the [`TimestampGuard`] and either
//! [`RespAccept::accept`]s (writing msg2, establishing the session) or
//! **drops** the accept — rejecting the peer with no msg2, WireGuard's
//! silent reject.

